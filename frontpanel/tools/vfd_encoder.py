"""
VFD frame encoder, based on the confirmed packing format:

    payload byte 1                 = header/reserved byte, always 0x00
    payload bytes [2+5s .. 6+5s]   = segment s's 5 bytes (s = 0..15)

Within a segment, each column is 7 rows tall, 5 columns wide (35 pixels),
packed as a continuous LSB-first bitstream across the segment's 5 bytes
(40 bits total, 5 unused trailing bits):

    stream = local_byte*8 + bit
    col = 5 - (stream % 5)      # 5,4,3,2,1
    row = 7 - (stream // 5)     # 7,6,5,4,3,2,1

This module lets you build a frame from a simple list of 16 segments,
each a 7x5 grid of booleans (row-major, row 0 = top, col 0 = left), and
get back the 82-byte transaction (including the leading 0x10 command byte)
ready to send over I2C.

NOTE: this format is confirmed from manual, one-bit-at-a-time testing on
real hardware (~87/89 sample points matched). It's solid but not
exhaustively verified across all 16 segments or all 5 header-byte values —
treat segment count / header byte meaning as provisional until you've
tried a full-panel frame and confirmed it looks right end to end.
"""

NUM_SEGMENTS = 16
ROWS = 7
COLS = 5
FRAME_CMD_BYTE = 0x10


def encode_segment(grid):
    """grid: 7x5 nested list/iterable of truthy/falsy, row-major (row0=top, col0=left).
    Returns a list of 5 ints (the segment's bytes)."""
    if len(grid) != ROWS or any(len(row) != COLS for row in grid):
        raise ValueError(f"grid must be {ROWS}x{COLS}")

    # Build the 35-bit stream in (col desc, row desc) order to match the
    # confirmed layout: stream position p -> col=5-(p%5), row=7-(p//5)
    bits = [0] * 40  # 5 bytes x 8 bits, last 5 stay 0 (dead padding)
    for p in range(35):
        col = 5 - (p % 5)          # 5..1
        row = 7 - (p // 5)         # 7..1
        pixel_on = bool(grid[ROWS - row][col - 1])  # grid is row-major; grid[0] is whatever
                                                       # you call "row 0" for input purposes.
                                                       # This matches the confirmed hardware
                                                       # (col,row) mapping from manual testing.
        bits[p] = 1 if pixel_on else 0

    out_bytes = []
    for b in range(5):
        val = 0
        for bit in range(8):
            if bits[b * 8 + bit]:
                val |= (1 << bit)
        out_bytes.append(val)
    return out_bytes


def encode_frame(segments, header_byte=0x00):
    """segments: list of up to 16 grids (7x5 booleans each). Missing segments
    are filled blank. Returns the full 82-byte list ready for
    Wire.beginTransmission(0x70) / Wire.write(bytes) / endTransmission()."""
    if len(segments) > NUM_SEGMENTS:
        raise ValueError(f"too many segments (max {NUM_SEGMENTS})")

    blank = [[0] * COLS for _ in range(ROWS)]
    padded = list(segments) + [blank] * (NUM_SEGMENTS - len(segments))

    payload = [header_byte]
    for seg in padded:
        payload.extend(encode_segment(seg))

    assert len(payload) == 81, f"internal error: payload should be 81 bytes, got {len(payload)}"
    return [FRAME_CMD_BYTE] + payload


