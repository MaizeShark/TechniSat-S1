def text_to_segments(text):
    """Convert a string to a list of 7x5 grids using FONT_5X7. Unknown
    characters (anything outside printable ASCII 32-126) render as blank.
    Truncates/pads to 16 segments.

    NOTE: testing showed glyphs render vertically flipped on the real
    hardware (confirmed via asymmetric glyphs '1' and 'L' -- symmetric
    ones like H/E/O/0 hid the bug). We flip each glyph's rows here, once,
    at output time -- so FONT_5X7 itself stays in the "natural" orientation
    (as you'd draw it on paper / as published in the source font) and this
    function corrects for the device's apparent row order.
    """
    grids = []
    for ch in text.upper()[:NUM_SEGMENTS]:
        glyph = FONT_5X7.get(ch, FONT_5X7[" "])
        grids.append(glyph[::-1])  # flip top<->bottom
    return grids


